#!/usr/bin/env node
/**
 * Embed the heli CLI into the distributed workspace so every install can run
 * `node .heli-harness/heli.mjs <cmd>` offline — no npx, no PATH, no network.
 *
 * Generated layout (committed, shipped via DISTRIBUTION_ENTRIES):
 *   .heli-harness/heli.mjs   <- bin/heli.mjs   (imports ../lib/cli/ -> ./cli/)
 *   .heli-harness/cli/*.mjs  <- lib/cli/*.mjs  (imports ../concurrency/ -> ../adapters/shared/concurrency/)
 *
 * Canonical source of truth: bin/heli.mjs + lib/cli/.
 * Run: node scripts/sync-workspace-cli.mjs
 * Check mode: node scripts/sync-workspace-cli.mjs --check
 */
import assert from "node:assert/strict";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const check = process.argv.includes("--check");

const HEADER = "// GENERATED by scripts/sync-workspace-cli.mjs — edit bin/heli.mjs + lib/cli/ instead.\n";

// Emit and compare pure LF: checkouts differ per platform (autocrlf), and a
// mixed-EOL generated file makes --check fail on whichever platform disagrees.
const lf = (text) => text.replaceAll("\r\n", "\n");

function renderEntry() {
	const src = lf(readFileSync(join(root, "bin", "heli.mjs"), "utf8"));
	const body = src.replaceAll('from "../lib/cli/', 'from "./cli/');
	// Keep the shebang first line, insert the generated header after it.
	return body.replace(/^(#![^\n]*\n)/, `$1${HEADER}`);
}

function renderCliModule(name) {
	const src = lf(readFileSync(join(root, "lib", "cli", name), "utf8"));
	return HEADER + src.replaceAll('from "../concurrency/', 'from "../adapters/shared/concurrency/');
}

const cliFiles = readdirSync(join(root, "lib", "cli")).filter((f) => f.endsWith(".mjs")).sort();
const expected = new Map([["heli.mjs", renderEntry()]]);
for (const name of cliFiles) {
	expected.set(join("cli", name).replaceAll("\\", "/"), renderCliModule(name));
}

const destRoot = join(root, ".heli-harness");

if (check) {
	for (const [rel, content] of expected) {
		const p = join(destRoot, rel);
		assert.ok(existsSync(p), `.heli-harness/${rel} missing — run: node scripts/sync-workspace-cli.mjs`);
		assert.equal(
			lf(readFileSync(p, "utf8")),
			content,
			`.heli-harness/${rel} differs from generated output — run sync-workspace-cli.mjs`,
		);
	}
	const actual = existsSync(join(destRoot, "cli"))
		? readdirSync(join(destRoot, "cli")).filter((f) => f.endsWith(".mjs")).sort()
		: [];
	assert.deepEqual(actual, cliFiles, ".heli-harness/cli file list differs from lib/cli");
	console.log("sync-workspace-cli --check: ok");
} else {
	if (existsSync(join(destRoot, "cli"))) rmSync(join(destRoot, "cli"), { recursive: true, force: true });
	mkdirSync(join(destRoot, "cli"), { recursive: true });
	for (const [rel, content] of expected) {
		writeFileSync(join(destRoot, rel), content);
	}
	console.log(`sync-workspace-cli: wrote heli.mjs + ${cliFiles.length} cli modules into .heli-harness`);
}
